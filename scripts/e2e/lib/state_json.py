"""Read the app's e2e state JSON, rejecting a duplicated member.

A duplicated member is valid RFC 8259 and Python's last-wins silently accepts it, so a key emitted
twice (from two call sites, or a copy-paste) reads as a working gate while the value a scenario sees
may not be the one it thinks it is. The state file is generated by the app, so a duplicate is always
a bug in the writer, and it should fail the scenario that read it rather than be papered over.

Usage:

    from state_json import load_state
    with open(state_path) as handle:
        state = load_state(handle)

A read failure propagates: a scenario must not continue on an empty state.

Run the self-test with `python3 scripts/e2e/lib/state_json.py`.
"""

from __future__ import annotations

import json


def _no_duplicate_members(pairs):
    """`object_pairs_hook` that rejects a member repeated in one object."""
    seen = set()
    for key, _ in pairs:
        if key in seen:
            raise ValueError(f"duplicate JSON member in the e2e state: {key}")
        seen.add(key)
    return dict(pairs)


def load_state(handle):
    """Parse the state document, refusing a duplicated member."""
    return json.load(handle, object_pairs_hook=_no_duplicate_members)


def _selftest() -> None:
    import io

    # A normal document reads back as before.
    normal = io.StringIO('{"a": 1, "b": {"c": 2, "d": 3}}')
    assert load_state(normal) == {"a": 1, "b": {"c": 2, "d": 3}}

    # A duplicated member at the top level is refused -- this is the real
    # switcher_footer_settings shape that passed the gate before.
    dup_top = io.StringIO('{"switcher_footer_settings": {"x": 1}, "other": 2, "switcher_footer_settings": {"x": 2}}')
    try:
        load_state(dup_top)
    except ValueError as error:
        assert "switcher_footer_settings" in str(error), error
    else:
        raise AssertionError("a duplicated top-level member was accepted")

    # A duplicated member in a nested object is refused too.
    dup_nested = io.StringIO('{"outer": {"k": 1, "k": 2}}')
    try:
        load_state(dup_nested)
    except ValueError as error:
        assert "k" in str(error), error
    else:
        raise AssertionError("a duplicated nested member was accepted")

    # Distinct members with the same value are NOT a duplicate.
    assert load_state(io.StringIO('{"a": 1, "b": 1}')) == {"a": 1, "b": 1}

    print("state_json selftest: ok")


if __name__ == "__main__":
    _selftest()
